// Converts a display name into a URL/database-safe slug.
// "JavaScript & Node" -> "javascript-node"
export function slugify(input: string): string {
  return input
    .toLowerCase()
    .trim()
    .replace(/[’']/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .replace(/-{2,}/g, "-");
}